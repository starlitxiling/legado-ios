        for (input, title, expected) in samples {
            XCTAssertEqual(try ContentHelp.reSegment(input, chapterName: title, random: { 0.5 }), expected, input)
        }
    }
    func testKotlinRandomSplitBranches() throws {
        let samples: [(String, Double, String)] = [
            ("甲。乙。丙。丁。戊。己。庚。辛。壬。癸。", 0.0, "甲。\n乙。\n丙。\n丁。\n戊。\n己。\n庚。\n辛。\n壬。\n癸。"),
            ("他说：“甲。乙。丙。丁。戊。己。庚。辛。壬。癸。”", 0.0, "他说：“甲。乙。丙。\n丁。戊。己。\n庚。辛。壬。\n癸。”\n"),
            ("甲，乙，丙，丁，戊。己，庚，辛，壬。癸，子，丑，寅。卯，辰，巳，午。未。申。酉。戌。亥。", 0.0, "甲，乙，丙，丁，戊。\n己，庚，辛，壬。\n癸，子，丑，寅。\n卯，辰，巳，午。\n未。\n申。\n酉。\n戌。\n亥。"),
            ("甲。乙。丙。丁。戊。己。庚。辛。壬。癸。", 0.99, "甲。乙。丙。丁。戊。己。庚。辛。壬。癸。"),
            ("他说：“甲。乙。丙。丁。戊。己。庚。辛。壬。癸。”", 0.99, "他说：“甲。乙。丙。丁。戊。己。庚。辛。壬。癸。”"),
            ("甲，乙，丙，丁，戊。己，庚，辛，壬。癸，子，丑，寅。卯，辰，巳，午。未。申。酉。戌。亥。", 0.99, "甲，乙，丙，丁，戊。己，庚，辛，壬。癸，子，丑，寅。卯，辰，巳，午。未。申。酉。戌。亥。"),
        ]
        for (input, random, expected) in samples {
            XCTAssertEqual(try ContentHelp.reSegment(input, chapterName: "", random: { random }), expected)
        }
    }
}
