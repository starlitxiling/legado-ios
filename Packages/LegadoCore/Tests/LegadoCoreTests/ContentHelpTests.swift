import XCTest
@testable import LegadoCore

final class ContentHelpTests: XCTestCase {
    func testKotlinResegmentSamplesWithFixedRandom() throws {
        let samples: [(String, String, String)] = [
            ("", "", ""),
            ("第一章\n太阳照在山上。\n风吹过来。", "第一章", "太阳照在山上。\n风吹过来。"),
            ("第一\n段没有\n结束。\n第二段开始。", "Title", "第一段没有结束。\n第二段开始。"),
            ("丫姑折断几枝扔下来，边叫我的小名儿边说：“先喂饱你！”", "", "丫姑折断几枝扔下来，边叫我的小名儿边说：“先喂饱你！”"),
            ("“哎呀，真是美极了！”皇帝说，“我十分满意！”", "", "“哎呀，真是美极了！”\n皇帝说，“我十分满意！”\n"),
            ("“怕什么！海的美就在这里！”我说道。", "", "“怕什么！海的美就在这里！”我说道。\n"),
            ("适当地改善自己的生活，岂但“你管得着吗”，而且是顺乎天理，合乎人情的。", "", "适当地改善自己的生活，岂但“你管得着吗”，而且是顺乎天理，合乎人情的。"),
            ("现代画家徐悲鸿笔下的马，正如有的评论家所说的那样，“形神兼备，充满生机”。", "", "现代画家徐悲鸿笔下的马，正如有的评论家所说的那样，“形神兼备，充满生机”。"),
            ("唐朝的张嘉贞说它“制造奇特，人不知其所为”。", "", "唐朝的张嘉贞说它“制造奇特，人不知其所为”。"),
            ("他说：\"你好。\"她说：\"再见。\"", "", "他说：“你好。”\n她说：“再见。”\n"),
            ("“锅”、“碗”和“杯”都是“器具”。这些“器具”有用。", "", "“锅”、“碗”和“杯”\n“都是”器具“。这些”器具“有用。”"),
            ("“一句。”\n“二句。”\n“第三句。”他说。", "", "“一句。”\n“二句。”\n“第三句。”他说。\n"),
            ("甲。乙。丙。丁。戊。己。庚。辛。壬。癸。", "", "甲。乙。丙。丁。戊。己。庚。辛。壬。癸。"),
            ("他说：“甲。乙。丙。丁。戊。己。庚。辛。壬。癸。”", "", "他说：“甲。乙。丙。丁。戊。己。庚。辛。壬。癸。”"),
            ("　这是 一段 \t 有 空格 的文字。\n\n这是下一段。", "", "这是一段有空格的文字。\n这是下一段。"),
            ("甲 &quot;乙&quot; 丙", "", "甲“乙”丙"),
            ("“", "", "”"),
            ("”", "", "”"),
            ("\"\"", "", "”\n“"),
            ("他说：\n“你好。”\n她答：“你好。”", "", "他说：“你好。”\n她答：“你好。”"),
            ("A😀B\nC。\nD😀E。", "", "A😀BC。\nD😀E。"),
